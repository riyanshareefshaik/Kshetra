export function t(key, lang = "en", vars = {}) {
  const row = T[key];
  let s = row ? (row[IDX[lang] ?? 0] || row[0]) : key;
  for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}

